package adeflow_test

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"

	"github.com/kirathecat/kira-studio/apps/kira-space/internal/adeflow"
	"github.com/kirathecat/kira-studio/apps/kira-space/internal/flowharness"
	"github.com/kirathecat/kira-studio/internal/configfs"
	"github.com/kirathecat/kira-studio/internal/configfs/configsvc"
	"github.com/kirathecat/kira-studio/internal/harness/providers"
)

var yamlFence = regexp.MustCompile("(?s)```yaml\n(.*?)```")

// TestWorkflowsAgentsDoc: Space start writes the workflows AGENTS.md; it names every option, enum
// value, rule and agent setting, its examples validate, and it is regenerated over edits.
func TestWorkflowsAgentsDoc(t *testing.T) {
	app := flowharness.New(t)
	dir := filepath.Join(app.SpaceHome, "workflows")
	path := filepath.Join(dir, "AGENTS.md")
	want := configfs.RenderAgentsMD(adeflow.DocModel())

	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) || !strings.HasPrefix(string(got), "<!-- Generated by Kira Space.") {
		t.Fatalf("AGENTS.md is not the generated file:\n%s", got)
	}
	doc := string(got)

	var need []string
	for _, o := range adeflow.DocModel().Options {
		need = append(need, o.Path)
		for _, e := range o.Enum {
			if !strings.Contains(doc, e) {
				t.Errorf("AGENTS.md lacks enum value %q of %s", e, o.Path)
			}
		}
	}
	for _, set := range providers.StageCatalog() {
		for _, s := range set.Settings {
			need = append(need, fmt.Sprintf("steps[].settings.%s.%s", set.ID, s.Key))
		}
	}
	for _, p := range need {
		if !strings.Contains(doc, "`"+p+"`") {
			t.Errorf("AGENTS.md lacks %q", p)
		}
	}
	for _, r := range adeflow.DocModel().Rules {
		if !strings.Contains(doc, r) {
			t.Errorf("AGENTS.md lacks rule %q", r)
		}
	}

	fences := yamlFence.FindAllStringSubmatch(doc, -1)
	if len(fences) == 0 {
		t.Fatal("AGENTS.md has no yaml example")
	}
	for _, f := range fences {
		if v := adeflow.ValidateYaml(f[1]); v.Error != nil {
			t.Errorf("example invalid: line %d: %s", v.Error.Line, v.Error.Message)
		}
	}

	if _, ok := fileEntry(t, app, "AGENTS.md"); ok {
		t.Error("AGENTS.md listed as a workflow")
	}
	if _, ok := lastValidRow(t, app, "AGENTS.md"); ok {
		t.Error("AGENTS.md has a last-valid row")
	}

	if err := os.WriteFile(path, []byte("junk"), 0o644); err != nil {
		t.Fatal(err)
	}
	app.Restart()
	if got, _ := os.ReadFile(path); !bytes.Equal(got, want) {
		t.Errorf("AGENTS.md not regenerated at start: %q", got)
	}

	if err := app.W.ConfigFiles.Open(configsvc.FileArgs{Folder: "workflows", File: "AGENTS.md"}); err != nil {
		t.Fatal(err)
	}
	if got := app.FileOpener.OpenedFiles(); len(got) != 1 || got[0] != path {
		t.Errorf("opened = %v, want [%s]", got, path)
	}
}

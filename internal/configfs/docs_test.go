package configfs

import (
	"strings"
	"testing"
)

// TestAgentsDocCoversSchema is the drift guard: every schema property path and rule doc is rendered.
func TestAgentsDocCoversSchema(t *testing.T) {
	rule := Rule[probe]{Doc: "retries must stay below five for mode fast.", Check: func(probe, Locator) *Problem { return nil }}
	_, model, err := YAMLSchema[probe](probeSchema, rule)
	if err != nil {
		t.Fatal(err)
	}
	model.App, model.Title, model.Pattern, model.Format = "Space", "Probes", "<id>.yaml", "YAML"
	out := string(RenderAgentsMD(model))
	for _, path := range []string{"name", "retries", "mode", "target", "target.url", "target.headers", "target.headers.*", "tags", "tags[]"} {
		if !strings.Contains(out, "`"+path+"`") {
			t.Errorf("option %s missing", path)
		}
	}
	for _, want := range []string{rule.Doc, "## References", "Generated by Kira Space", "default `1`", "one of \"fast\", \"safe\"", "one secret reference"} {
		if !strings.Contains(out, want) {
			t.Errorf("%q missing", want)
		}
	}
}

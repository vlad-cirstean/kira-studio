func goUnits(t *testing.T, src string, min int) ([]Comment, []Unit) {
	t.Helper()
	gs, generated, err := goGroups("x.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	status := ""
	if generated {
		status = stGenerated
	}
	return classify("x.go", "go", []byte(src), gs, status, "", min, 2000)
}

func statuses(cs []Comment) []string {
	var out []string
	for _, c := range cs {
		out = append(out, c.Status)
	}
	return out
}

func TestGoEligibility(t *testing.T) {
	body := strings.Repeat("word ", 20)
	src := "package p\n\nfunc f() {\n\tx := 1 // " + body + "\n\t// " + body + "\n\t// " + body + "\n\ty := 2\n\t_, _ = x, y\n}\n"
	cs, us := goUnits(t, src, 100)
	if len(cs) != 2 || cs[0].Status != stNotWholeLine || len(us) != 1 {
		t.Fatalf("trailing comment must be excluded, the own-line group after it kept: %v", statuses(cs))
	}

	src = "package p\n\nfunc f() {\n\t// " + body + "\n\t// " + body + "\n\ty := 2\n\t_ = y\n}\n"
	cs, us = goUnits(t, src, 100)
	if len(us) != 1 || cs[0].Status != stEligible {
		t.Fatalf("whole-line group is one unit: %v", statuses(cs))
	}
	if !strings.HasPrefix(us[0].Text, "\t// ") || strings.Count(us[0].Text, "\n") != 1 || strings.HasSuffix(us[0].Text, "\n") {
		t.Fatalf("unit text must start at the first line's indent and end at the last comment byte: %q", us[0].Text)
	}
	if us[0].Line != 4 || string([]byte(src)[us[0].Start:us[0].End]) != us[0].Text {
		t.Fatalf("offsets: line %d start %d end %d", us[0].Line, us[0].Start, us[0].End)
	}

	cs, _ = goUnits(t, "package p\n\n// "+body+"\n//go:embed x.txt\nvar s string\n", 100)
	if cs[0].Status != stDirective {
		t.Fatalf("//go:embed in a doc group must skip the unit: %v", statuses(cs))
	}
	cs, _ = goUnits(t, "package p\n\n/*\n#include <stdio.h>\n// "+body+"\n*/\nimport \"C\"\n", 20)
	if cs[0].Status != stDirective || cs[0].Reason != "cgo preamble" {
		t.Fatalf("cgo preamble: %v %q", statuses(cs), cs[0].Reason)
	}
	cs, _ = goUnits(t, "// Code generated by x. DO NOT EDIT.\n\npackage p\n\n// "+body+"\nvar a int\n", 20)
	for _, c := range cs {
		if c.Status != stGenerated {
			t.Fatalf("generated file: %v", statuses(cs))
		}
	}
	cs, _ = goUnits(t, "package p\n\n// "+body+"\nvar a int\n", 2000)
	if cs[0].Status != stBelowMin {
		t.Fatalf("below min: %v", statuses(cs))
	}
}

func TestTSRunGrouping(t *testing.T) {
	src := "  // a\n  // b\n\n  // c\n// d\n  // e\n  x(); // f\n  // g\n  /* h */ /* i */\n"
	ranges := []rawRange{}
	off := 0
	for _, l := range strings.SplitAfter(src, "\n") {
		for _, tok := range []string{"// ", "/* "} {
			for from := 0; ; {
				i := strings.Index(l[from:], tok)
				if i < 0 {
					break
				}
				s := off + from + i
				if tok == "// " {
					ranges = append(ranges, rawRange{Start: s, End: off + len(strings.TrimRight(l, "\n")), Kind: "line"})
					break
				}
				e := strings.Index(l[from+i:], "*/") + from + i + 2
				ranges = append(ranges, rawRange{Start: s, End: off + e, Kind: "block"})
				from = e
			}
		}
		off += len(l)
	}
	var got []string
	for _, g := range tsGroups([]byte(src), ranges) {
		got = append(got, strings.ReplaceAll(src[g.start:g.end], "\n", "|"))
	}
	want := []string{"// a|  // b", "// c", "// d", "// e", "// f", "// g", "/* h */", "/* i */"}
	if strings.Join(got, ";") != strings.Join(want, ";") {
		t.Fatalf("groups: %q want %q", got, want)
	}
}

func TestContextCap(t *testing.T) {
	var lines []string
	for range 40 {
		lines = append(lines, strings.Repeat("x", 299))
	}
	src := []byte(strings.Join(lines, "\n") + "\n")
	idx := newLineIndex(src)
	ctx := contextOf(src, idx, 10, 10)
	if n := utf8.RuneCountInString(ctx); n > ctxMaxRunes {
		t.Fatalf("context %d runes", n)
	}
	for _, l := range strings.Split(ctx, "\n") {
		if len(l) != 299 {
			t.Fatalf("context must be cut at a line boundary, got a %d-char line", len(l))
		}
	}
	if got := strings.Count(ctx, "\n") + 1; got != 20 {
		t.Fatalf("expected 5 before and 15 after to fit 6000 runes, got %d lines", got)
	}
}
